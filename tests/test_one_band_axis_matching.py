"""Bounded checks for native one-band axis matching, not a general search."""
from __future__ import annotations

import itertools
import unittest

import numpy as np

from tests.test_read_only_three_layer_rigidity import H, S, T, _cx, _pauli, _wire


def _paulis(n):
    return [1j ** (p & q).bit_count() * _pauli(p, q, n)
            for q in range(1 << n) for p in range(1 << n)]


def _coefficients(operator, paulis):
    return np.array([np.trace(p @ operator) / operator.shape[0]
                     for p in paulis])


def _is_clifford(operator, paulis):
    for p in paulis:
        image = operator @ p @ operator.conj().T
        if max(abs(_coefficients(image, paulis))) < 1 - 1e-10:
            return False
    return True


def _same_axis(p, q):
    return abs(np.trace(p @ q) / p.shape[0]) > 1 - 1e-10


def _matches(c, left, right):
    images = [c @ p @ c.conj().T for p in right]
    return (len(left) == len(right)
            and all(any(_same_axis(p, q) for q in left) for p in images))


def _one_qubit_cliffords():
    """The 24 projective Cliffords, generated by native H and S."""
    result = [np.eye(2, dtype=complex)]
    todo = [result[0]]
    while todo:
        u = todo.pop()
        for gate in (H, S):
            candidate = gate @ u
            if not any(abs(np.trace(v.conj().T @ candidate)) / 2 > 1 - 1e-10
                       for v in result):
                result.append(candidate)
                todo.append(candidate)
    return result


def _projective_distance(u, v):
    """Minimize operator distance over the scalar phase via an eigenvalue arc."""
    angles = np.sort(np.angle(np.linalg.eigvals(u.conj().T @ v)))
    gaps = np.diff(np.append(angles, angles[0] + 2 * np.pi))
    arc = 2 * np.pi - max(gaps)
    return 2 * np.sin(arc / 4)


class OneBandAxisMatching(unittest.TestCase):
    def test_independent_axis_expansion_and_fourier_recovery(self):
        paulis = _paulis(2)
        identity = np.eye(4, dtype=complex)
        x0, x1 = _wire(np.array([[0, 1], [1, 0]]), 0), _wire(np.array([[0, 1], [1, 0]]), 1)
        z0, z1 = _wire(np.diag([1, -1]), 0), _wire(np.diag([1, -1]), 1)
        basis = _cx(0, 1) @ _wire(H, 0)
        for d, axes in [(identity, []), (_wire(T, 0), [z0]),
                        (_wire(T, 0) @ _wire(T.conj().T, 1), [z0, z1]),
                        (basis @ _wire(T, 0) @ _wire(T.conj().T, 1)
                         @ basis.conj().T,
                         [basis @ z0 @ basis.conj().T,
                          basis @ z1 @ basis.conj().T])]:
            values = []
            for p in paulis:
                k = sum(np.linalg.norm(a @ p - p @ a) > 1 for a in axes)
                values.append(k)
                coeffs = _coefficients(d @ p @ d.conj().T, paulis)
                nonzero = abs(coeffs) > 1e-10
                self.assertEqual(int(sum(nonzero)), 1 << k)
                np.testing.assert_allclose(abs(coeffs[nonzero]), 2 ** (-k / 2), atol=2e-14)
                self.assertAlmostEqual(sum(abs(coeffs)), 2 ** (k / 2))
            recovered = []
            for a in paulis[1:]:
                chars = [1 if np.linalg.norm(a @ p - p @ a) < 1e-10 else -1
                         for p in paulis]
                coefficient = np.dot(chars, values) / len(paulis)
                if abs(coefficient) > 1e-10:
                    self.assertAlmostEqual(coefficient, -0.5)
                    recovered.append(a)
            self.assertTrue(_matches(identity, axes, recovered))
        # Fixed-basis conjugation need not leave the physical Z list unchanged.
        self.assertFalse(_same_axis(x0, z0))
        self.assertFalse(_same_axis(x1, z1))

    def test_native_matching_with_inactive_wires_and_orientations(self):
        paulis = _paulis(2)
        z0, z1 = _wire(np.diag([1, -1]), 0), _wire(np.diag([1, -1]), 1)
        swap = _cx(0, 1) @ _cx(1, 0) @ _cx(0, 1)
        layers = [(np.eye(4), []), (_wire(T, 0), [z0]),
                  (_wire(T.conj().T, 1), [z1]),
                  (_wire(T, 0) @ _wire(T.conj().T, 1), [z0, z1])]
        words = [np.eye(4), swap, _cx(0, 1), _cx(1, 0),
                 _wire(H, 0), _wire(S, 0),
                 _wire(H @ S @ S @ H, 0),
                 _cx(0, 1) @ _wire(H, 1),
                 swap @ _wire(S, 0) @ _wire(H, 1)]
        for (d, left), (e, right), c in itertools.product(layers, layers, words):
            candidate = d @ c @ e.conj().T
            self.assertEqual(_is_clifford(candidate, paulis),
                             _matches(c, left, right))
        # Span preservation is weaker than preservation of the native axis list.
        self.assertFalse(_matches(_cx(0, 1), [z0, z1], [z0, z1]))
        self.assertTrue(_matches(_cx(0, 1), [z0], [z0]))

    def test_robust_radius_against_all_one_qubit_cliffords(self):
        cliffords = _one_qubit_cliffords()
        self.assertEqual(len(cliffords), 24)
        z = np.diag([1, -1]).astype(complex)
        for c in cliffords:
            actual = T @ c @ T.conj().T
            distance = min(_projective_distance(actual, other)
                           for other in cliffords)
            if _matches(c, [z], [z]):
                self.assertLess(distance, 3e-8)
            else:
                self.assertGreaterEqual(distance + 2e-12, np.sqrt(2) / 4)

    def test_complete_cancellation_does_not_make_first_passage_clifford(self):
        paulis = _paulis(1)
        x = np.array([[0, 1], [1, 0]], dtype=complex)
        y = np.array([[0, -1j], [1j, 0]], dtype=complex)
        a = T.conj().T @ x @ T
        b = T @ a @ T.conj().T
        np.testing.assert_allclose(a, (x - y) / np.sqrt(2), atol=2e-14)
        np.testing.assert_allclose(b, x, atol=2e-14)
        self.assertTrue(_is_clifford(a, paulis))
        self.assertTrue(_is_clifford(b @ H @ b.conj().T, paulis))
        self.assertFalse(_is_clifford(T.conj().T @ H @ T, paulis))
        # X=HSSH costs four elementary Cliffords. Displayed B and BHB-
        # dagger charge every actual call/inverse; the target is arbitrary.
        word = ["T", "Tdg", "H", "S", "S", "H", "T", "Tdg"]
        gates = {"T": T, "Tdg": T.conj().T, "H": H, "S": S}
        native = np.eye(2, dtype=complex)
        for gate in word:
            native = gates[gate] @ native
        np.testing.assert_allclose(native, b, atol=2e-14)
        t_count = sum(gate in ("T", "Tdg") for gate in word)
        cliffords = len(word) - t_count
        self.assertEqual((t_count, t_count, cliffords, 0, 0), (4, 4, 4, 0, 0))
        self.assertEqual((2 * t_count, 2 * t_count, 2 * cliffords + 1, 0, 0),
                         (8, 8, 9, 0, 0))


if __name__ == "__main__":
    unittest.main()
