"""Finite checks for hybrid diagonal / bounded-core transport mechanisms.

The proof supplies the arbitrary-width theorem. These fixtures test the
ordered controlled-Pauli phase, four-block signed recovery, and literal
localization in both source orderings, plus a monomial localization with
a nontrivial isotropic intersection. The generic localization source
need not be C3; that check does not assert the transport theorem's C3
hypothesis or construct a native returned query.
"""
from __future__ import annotations

import itertools
import math
import unittest

import numpy as np

from tests.test_outer_axis_normalizer import _tau
from tests.test_read_only_three_layer_rigidity import H, S, T, X, Z, _cx, _wire


def _block(matrix, controls):
    """The wire-zero block at a computational string on all other wires."""
    indices = [2 * controls, 2 * controls + 1]
    return matrix[np.ix_(indices, indices)]


def _cz(left, right, width):
    return _wire(H, right, width) @ _cx(left, right, width) @ _wire(H, right, width)


class HybridDiagonalCoreTransport(unittest.TestCase):
    def test_monomial_localization_preserves_diagonal_coordinates(self):
        # An isotropic rank-four space on six wires. Its Z intersection
        # has rank two; both its X projection and Z tails use remote wires.
        # The labels are supplied directly, rather than generated by the
        # localizing word under test. Low six bits are X, high six are Z.
        width = 6
        mask = (1 << width) - 1
        basis = [2917, 282, 2304, 1536]
        undo_linear = [("CX", 4, 3), ("CX", 5, 2), ("CX", 3, 1),
                       ("CX", 1, 4), ("CX", 2, 0), ("CX", 0, 5)]
        remove_tails = [("CZ", 1, 5), ("CZ", 1, 2), ("CZ", 0, 4),
                        ("CZ", 0, 3), ("CZ", 0, 1), ("S", 0)]
        word = undo_linear + remove_tails

        def pair(left, right):
            return (((left & mask) & (right >> width)).bit_count()
                    + ((right & mask) & (left >> width)).bit_count()) % 2

        def image(label):
            x, z = label & mask, label >> width
            for gate in word:
                if gate[0] == "S":
                    wire = gate[1]
                    z ^= ((x >> wire) & 1) << wire
                else:
                    control, target = gate[1:]
                    if gate[0] == "CX":
                        x ^= ((x >> control) & 1) << target
                        z ^= ((z >> target) & 1) << control
                    else:
                        z ^= (((x >> control) & 1) << target
                              ^ ((x >> target) & 1) << control)
            return x | (z << width)

        def span(generators):
            result = {0}
            for generator in generators:
                result |= {label ^ generator for label in tuple(result)}
            return result

        original = span(basis)
        self.assertEqual(len(original), 16)
        self.assertEqual(sum(label & mask == 0 for label in original), 4)
        self.assertTrue(all(pair(left, right) == 0
                            for left, right in itertools.product(original, repeat=2)))
        self.assertTrue(any((label & mask) >> 4 for label in original))
        self.assertTrue(any((label >> width) >> 4 for label in original))
        canonical = [1, 2, 4 << width, 8 << width]
        self.assertEqual([image(label) for label in basis], canonical)
        self.assertEqual({image(label) for label in original}, span(canonical))

        # Preserving every Z direction is the condition that lets the wide
        # diagonal phase survive this same localization. Check it separately
        # from mapping the particular isotropic space into four wires.
        diagonal_space = {z << width for z in range(1 << width)}
        self.assertEqual({image(label) for label in diagonal_space}, diagonal_space)
        pauli_basis = [1 << j for j in range(2 * width)]
        for left, right in itertools.product(pauli_basis, repeat=2):
            self.assertEqual(pair(image(left), image(right)), pair(left, right))

    def test_ordered_controlled_paulis_retain_mod_four_phase(self):
        # Four distinct controls, with noncommuting core axes X, Z, Y, X.
        axes = [(1, 0), (0, 1), (1, 1), (1, 0)]
        width = 5
        zero = np.diag([1, 0]).astype(complex)
        one = np.diag([0, 1]).astype(complex)
        controlled = np.eye(1 << width, dtype=complex)
        for j, (alpha, beta) in enumerate(axes):
            gate = (_wire(zero, j + 1, width)
                    + _wire(one, j + 1, width)
                    @ _wire(_tau(alpha | (beta << 1), 1), 0, width))
            controlled = controlled @ gate

        saw_cross_phase = saw_imaginary_phase = False
        for word in range(16):
            bits = [(word >> j) & 1 for j in range(4)]
            u = sum(alpha * bit for (alpha, _), bit in zip(axes, bits)) % 2
            v = sum(beta * bit for (_, beta), bit in zip(axes, bits)) % 2
            linear = sum(alpha * beta * bit
                         for (alpha, beta), bit in zip(axes, bits))
            cross = 2 * sum(axes[j][1] * axes[k][0] * bits[j] * bits[k]
                            for j in range(4) for k in range(j + 1, 4))
            phase = (linear + cross) % 4
            expected = (1j ** phase * np.linalg.matrix_power(X, u)
                        @ np.linalg.matrix_power(Z, v))
            np.testing.assert_allclose(_block(controlled, word), expected, atol=2e-14)
            saw_cross_phase |= cross % 4 == 2
            saw_imaginary_phase |= phase % 2 == 1
        self.assertTrue(saw_cross_phase)
        self.assertTrue(saw_imaginary_phase)

        # Ordered controlled Paulis have the claimed signed tail action,
        # including when their core axes anticommute with each other.
        for label in range(4):
            x, z = label & 1, label >> 1
            tail = sum(((alpha * z + beta * x) % 2) << (j + 1)
                       for j, (alpha, beta) in enumerate(axes))
            full_label = x | (z << width)
            actual = controlled @ _tau(full_label, width) @ controlled.conj().T
            expected = _tau(full_label | (tail << width), width)
            np.testing.assert_allclose(actual, expected, atol=2e-14)

    def test_four_blocks_recover_all_signed_three_qubit_probes(self):
        width = 3
        unitary = (_wire(H, 0, width) @ _cx(1, 0, width)
                   @ _wire(S, 0, width) @ _cx(2, 0, width)
                   @ _wire(S, 1, width))
        blocks = [_block(unitary, z) for z in range(4)]
        roots = [1, 1j, -1, -1j]
        saw_imaginary_alpha = saw_essential_carry = False
        largest_integer_dot = 0

        for probe in range(64):
            core = (probe & 1) | (((probe >> width) & 1) << 1)
            u, v = (probe >> 1) & 3, (probe >> (width + 1)) & 3

            def transition(z):
                return blocks[z ^ u] @ _tau(core, 1) @ blocks[z].conj().T

            at_zero = transition(0)
            coefficients = [np.trace(_tau(label, 1) @ at_zero) / 2
                            for label in range(4)]
            result_core = int(np.argmax(np.abs(coefficients)))
            mu = min(range(4), key=lambda j: abs(coefficients[result_core] - roots[j]))
            alpha = roots[mu]
            np.testing.assert_allclose(at_zero, alpha * _tau(result_core, 1), atol=3e-14)
            saw_imaginary_alpha |= mu % 2 == 1

            result_v = v
            for j in range(2):
                # This uses only blocks at 0, u, e_j, e_j+u.
                ratio = transition(1 << j) @ at_zero.conj().T
                bit = int(np.trace(ratio).real < 0)
                np.testing.assert_allclose(ratio, (-1) ** bit * np.eye(2), atol=3e-14)
                result_v ^= bit << j

            output_dot, input_dot = (u & result_v).bit_count(), (u & v).bit_count()
            even_phase = (mu - output_dot + input_dot) % 4
            self.assertEqual(even_phase % 2, 0)
            sign = even_phase // 2
            largest_integer_dot = max(largest_integer_dot, output_dot)
            parity_only_sign = (mu - (output_dot % 2) + (input_dot % 2)) % 4 // 2
            saw_essential_carry |= parity_only_sign != sign
            result = ((result_core & 1) | (u << 1)
                      | ((result_core >> 1) << width)
                      | (result_v << (width + 1)))
            actual = unitary @ _tau(probe, width) @ unitary.conj().T
            np.testing.assert_allclose(actual, (-1) ** sign * _tau(result, width), atol=3e-14)

        self.assertTrue(saw_imaginary_alpha)
        self.assertGreaterEqual(largest_integer_dot, 2)
        self.assertTrue(saw_essential_carry)

    def test_signed_spectator_localization_in_both_hybrid_orderings(self):
        width = 4  # A=0, B1=1, B2=2, B3=3.
        axis = (X + math.sqrt(2) * _tau(3, 1) + math.pi * Z) / math.sqrt(3 + math.pi**2)
        angle = math.pi / 7
        local = math.cos(angle) * np.eye(2) + 1j * math.sin(angle) * axis
        for label in (1, 2, 3):
            image = local @ _tau(label, 1) @ local.conj().T
            coefficients = [np.trace(_tau(p, 1) @ image) / 2 for p in range(4)]
            self.assertLess(max(abs(value) for value in coefficients), 1 - 1e-4)

        core = _wire(local, 0, width)
        core_cz, spectator_cz = _cz(0, 1, width), _cz(1, 3, width)
        unsigned_match = _wire(S, 3, width) @ spectator_cz
        signed_match = _wire(Z, 3, width) @ unsigned_match
        diagonal = signed_match @ core_cz @ _wire(T, 2, width)
        expected = core @ _wire(T, 2, width)
        identity = np.eye(1 << width, dtype=complex)

        for ordering in ("DU", "UD"):
            with self.subTest(ordering=ordering):
                source = diagonal @ core if ordering == "DU" else core @ diagonal
                # R0 is the B3 translation direction. Its image is -Y3 Z1:
                # this has both a deliberate sign and an odd Hermitian phase.
                translation = _tau(1 << 3, width)
                image_label = (1 << 3) | (((1 << 1) | (1 << 3)) << width)
                signed_image = -_tau(image_label, width)
                for operator in (diagonal, signed_match, source):
                    np.testing.assert_allclose(operator @ translation @ operator.conj().T,
                                               signed_image, atol=4e-14)

                stripped = signed_match.conj().T @ source
                residual = core_cz @ _wire(T, 2, width)
                expected_stripped = residual @ core if ordering == "DU" else core @ residual
                np.testing.assert_allclose(stripped, expected_stripped, atol=4e-14)

                # C0 matches the remaining signed core action. V puts its
                # input domain in canonical form; for UD it is the same CZ.
                coordinates = identity if ordering == "DU" else core_cz
                localized = coordinates.conj().T @ core_cz.conj().T @ stripped @ coordinates
                np.testing.assert_allclose(localized, expected, atol=5e-14)
                # The literal identity factors are B1,B3; B2 is a Z control,
                # leaving q=1 despite a degenerate Pauli-preserving domain.
                for sx, sz, radical in itertools.product(range(4), range(4), range(2)):
                    x = ((sx & 1) << 1) | ((sx >> 1) << 3)
                    z = ((sz & 1) << 1) | ((sz >> 1) << 3) | (radical << 2)
                    pauli = _tau(x | (z << width), width)
                    np.testing.assert_allclose(localized @ pauli, pauli @ localized, atol=5e-14)

                wrong = (coordinates.conj().T @ core_cz.conj().T
                         @ unsigned_match.conj().T @ source @ coordinates)
                np.testing.assert_allclose(wrong, _wire(Z, 3, width) @ expected, atol=5e-14)
                np.testing.assert_allclose(wrong @ translation @ wrong.conj().T,
                                           -translation, atol=6e-14)
                self.assertGreater(np.linalg.norm(wrong @ translation - translation @ wrong, 2), 1)


if __name__ == "__main__":
    unittest.main()
